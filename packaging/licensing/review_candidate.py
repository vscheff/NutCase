"""Explicit current candidate audit. Never called by a build or release gate.

Carry forward exact baseline candidate origins, reject new/changed dependency binaries,
and apply only the decisions supported by the retained current candidate investigation.
This is not an approval generator for arbitrary future payloads.
"""
import copy
import argparse
import csv
import json
import shutil
from pathlib import Path
from research import ROOT, digest
from assemble import sbom, write_json

REVIEW=ROOT/'packaging/licensing'
OUT=ROOT/'artifacts/licensing-candidate'
RESEARCH=OUT/'research'
BASELINE=OUT/'baseline/licensing/inventory.json'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--candidate',type=Path,default=OUT/'candidate-bundle')
    parser.add_argument('--allow-removed-resource',action='append',default=[],
                        help='Explicitly reviewed removal of an authored documentation resource')
    args=parser.parse_args()
    old=json.loads(BASELINE.read_text(encoding='utf-8'))
    original={r['path']:r for r in old['files']}
    bundle=ROOT/'dist/NutCase'
    candidate=args.candidate
    from sys import path as python_path
    python_path.insert(0,str(ROOT/'packaging'))
    from prepare_bundle import installer_payload
    installer_payload(candidate,bundle)
    actual={p.relative_to(candidate).as_posix():p for p in candidate.rglob('*') if p.is_file()}
    rows=[]
    for name,path in sorted(actual.items()):
        native=path.suffix.lower() in ('.dll','.pyd','.exe')
        if native and name not in original:raise ValueError('Unreviewed native file: '+name)
        if native and name not in ('NutCase.exe','NutCaseWorker.exe') and digest(path)!=original[name]['sha256']:
            raise ValueError('Changed dependency requires independent origin review: '+name)
        if name in original:
            row=copy.deepcopy(original[name]);row.update(sha256=digest(path),size=path.stat().st_size)
            if row['sha256']!=original[name]['sha256']:
                if native:row['provenance']=[{'origin':'NutCase rebuilt from current source using pinned PyInstaller; actual CArchive/PYZ decoded in embedded-python.json; build TOCs retained'}]
                elif name=='_internal/base_library.zip':row['provenance']=[{'origin':'Pinned CPython standard-library bytecode ZIP generated by PyInstaller; decoded member inventory retained'}]
                elif name.startswith(('native-src/','docs/','licenses/')) or '/' not in name:
                    row['provenance']=[{'origin':'Explicit current candidate source/documentation/notice remediation; previous content hash retained in baseline','previous_sha256':original[name]['sha256']}]
                else:raise ValueError('Unreviewed changed resource: '+name)
        else:
            if name.startswith('licenses/'):component='notice-resources'
            elif name.startswith(('docs/','native-src/')):component='nutcase-source-resources'
            else:raise ValueError('Unreviewed new resource: '+name)
            row={'path':name,'installed_path':'{app}/'+name,'sha256':digest(path),'size':path.stat().st_size,
                 'component':component,'provenance':[{'origin':'Explicit current candidate retained official SDK/codec notice or authored audit document'}],
                 'pe':None,'copyright':'See exact notice or authored source document'}
        rows.append(row)
    removed=[r for r in old['files'] if r['path'] not in actual]
    for row in removed:
        name=row['path']
        if name in args.allow_removed_resource and row['component']=='nutcase-source-resources' and Path(name).suffix.lower() in ('.md','.json','.zip'):
            continue
        if not (name.startswith('_internal/PySide6/translations/') and name.endswith('.qm')) and not name.startswith('_internal/PySide6/plugins/'):
            raise ValueError('Unexpected removal: '+name)
    from qt_policy import verify_payload
    verify_payload(candidate)
    decisions={
      'qt-libraries-plugins':('VERIFIED','Native source/configured notice correspondence established: all retained SDK sections match, source tags and source-file checks match (EOL/tag/Git metadata differences recorded), official configured SDK notice SBOMs installed. Binding build correlation remains a separate blocker.'),
      'qt-pdf':('VERIFIED','Qt PDF/PdfWidgets sections match the standalone official 6.140.0 SDK. Source tag d505fc23640d2bd6345e6483eb73daf4e19f5829 matches the acquired full source; 1,771 source files match raw hashes. Actual configured Chromium-PDF notice SBOM installed. This does not approve the PySide Pdf binding build.'),
      'qt-translations':('NOT APPLICABLE','All 99 catalogs excluded before COLLECT. No application translator loading; explicit Qt translator semantics and four frozen locale tests establish English source fallback. Native Windows dialogs may use OS localization.'),
      'pyside6':('BLOCKED','Exact binding-wheel revisions, patches/configuration and binding-specific compiled notices remain unresolved, including PySide6_Pdf 6.12.0.140. Native Qt SDK correspondence is established separately; commercial reference does not imply commercial-only rights.'),
      'shiboken6':('BLOCKED','Official 6.12 source retained; exact binding wheel revision/configuration/patch and compiled notice correspondence still need upstream evidence.'),
      'qt-mesa-rasterizer':('BLOCKED','Code/data sections match official Qt Mesa variants and software context loads this DLL. Nominal Mesa 11.2.2/LLVM 3.6.2 notices plus Qt attribution retained; confirm compiled LLVM/auxiliary notice closure. Full-file differences are not a source-compliance requirement under known permissive terms.'),
      'pillow':('REQUIRES HUMAN/LEGAL REVIEW','Actual frozen codec selection measured; missing AOM license/patent text and full dav1d/recipe-selected libyuv notices added. Confirm secondary static closure (libyuv/libsharpyuv, TIFF/lzma) and residual attribution. FreeType extension absent; Tk adapter physically shipped but tkinter absent.'),
      'pypdfium2-pdfium':('REQUIRES HUMAN/LEGAL REVIEW','Exact binary-release, actual GN arguments, successful Windows builder job and 14 build-derived notices established; all notice bytes installed. Exact PDFium checkout unrecorded; source delivery not automatically required under BSD. Review sufficiency or obtain narrow maintainer confirmation of commit/unhandled notice warnings.'),
    }
    components=copy.deepcopy(old['components'])
    index=json.loads((REVIEW/'notices/NOTICE_INDEX.json').read_text())
    indexed={n['installed_notice'] for n in index}
    for path in sorted((REVIEW/'notices').iterdir()):
        target='licenses/audit/'+path.name
        if path.is_file() and path.name!='NOTICE_INDEX.json' and target not in indexed:
            index.append({'source_evidence':'current candidate official SDK/codec evidence: '+path.name,
                          'installed_notice':target,'sha256':digest(path)})
    write_json(REVIEW/'notices/NOTICE_INDEX.json',index)
    # The installed index was staged before this explicitly reviewed mapping.
    shutil.copy2(REVIEW/'notices/NOTICE_INDEX.json',candidate/'licenses/audit/NOTICE_INDEX.json')
    next(r for r in rows if r['path']=='licenses/audit/NOTICE_INDEX.json')['sha256']=digest(candidate/'licenses/audit/NOTICE_INDEX.json')
    next(r for r in rows if r['path']=='licenses/audit/NOTICE_INDEX.json')['size']=(candidate/'licenses/audit/NOTICE_INDEX.json').stat().st_size
    manifest={r['path']:r['sha256'] for r in rows if r['path']!='bundle-manifest.json'}
    write_json(candidate/'bundle-manifest.json',{'schema_version':1,'files':manifest})
    next(r for r in rows if r['path']=='bundle-manifest.json').update(sha256=digest(candidate/'bundle-manifest.json'),size=(candidate/'bundle-manifest.json').stat().st_size)
    for c in components:
        if c['id'] in decisions:c['status'],c['outstanding']=decisions[c['id']]
        matching=[r for r in rows if r['component']==c['id']];c['file_count']=len(matching)
        if c['id'] in decisions:c['evidence'].append('current candidate exact evidence in artifacts/licensing-candidate/research; archived candidate acceptance records states scope and limitations')
        if c['id'] in ('qt-libraries-plugins','qt-pdf'):
            names=('Qt-SDK-qtbase-6.12.0.spdx.json','Qt-SDK-qtsvg-6.12.0.spdx.json') if c['id']=='qt-libraries-plugins' else ('Qt-SDK-qtpdf-6.140.0.spdx.json','Qt-SDK-qtwebengine-chromium-pdf-6.140.0.spdx.json')
            c['notice_files'].extend('licenses/audit/'+n for n in names)
        if c['id']=='pillow':c['notice_files'].extend('licenses/audit/'+p.name for p in (REVIEW/'notices').glob('*.txt') if p.name.startswith(('aom-','dav1d-','libyuv-')))
        if c['id']=='qt-mesa-rasterizer':c['notice_files']=[n['installed_notice'] for n in index if n['source_evidence'].startswith(('mesa-11.2.2','llvm-3.6.2'))]+['licenses/audit/Qt-Mesa-official-attribution.html']
        for r in matching:r.update(component_name=c['name'],component_version=c['version'],license_expression=c['license_expression'],status=c['status'],outstanding=c['outstanding'],corresponding_source='source-manifest.json',build_information='BUILD_AND_REPLACEMENT.md')
    comparison={'baseline_native_count':110,'candidate_native_count':sum(Path(r['path']).suffix.lower() in ('.exe','.dll','.pyd') for r in rows),
                'removed':[{'path':r['path'],'size':r['size'],'sha256':r['sha256']} for r in removed],
                'removed_bytes':sum(r['size'] for r in removed),'all_retained_dependency_native_hashes_unchanged':True,
                'new_dependency_native_files':[],'rebuilt_application_exes':['NutCase.exe','NutCaseWorker.exe'],
                'baseline_payload_bytes':sum(r['size'] for r in old['files']),'candidate_payload_bytes':sum(r['size'] for r in rows)}
    write_json(RESEARCH/'payload-comparison.json',comparison)
    supplemental=[]
    for p in sorted(RESEARCH.rglob('*')):
        if not p.is_file():continue
        if p.suffix.lower() not in ('.json','.xml','.html','.md','.txt','.py','.sh','.cmd','.cmake','.pri','.spdx') and p.name!='libavif-1.4.2-source.tar.gz':continue
        if p.name.startswith('pyinstaller-') or p.name=='qt-source-correlation-summary.txt':continue
        supplemental.append({'path':p.relative_to(RESEARCH).as_posix(),'sha256':digest(p),'size':p.stat().st_size,
                             'role':'supplemental-source-build-notice-evidence','public_delivery':True,
                             'upstream':'See retained download receipts and references.json; authored analyses identify their inputs'})
    review={**old,'scope':'current candidate explicit dependency minimization and current frozen payload audit; original baseline candidate preserved',
            'installer':{'path':'artifacts/licensing-candidate/release/NutCase-0.6.0-windows-x64-setup.exe','sha256':'0'*64,'version':'0.6.0','compiler':'Inno Setup 7.1.0','inspection':'UNBOUND until actual isolated install'},
            'files':rows,'components':components,'supplemental_materials':supplemental,
            'obligations':json.loads((REVIEW/'obligations.json').read_text()),'installer_generated_files':[],
            'embedded_python':json.loads((REVIEW/'embedded-python.json').read_text())}
    write_json(REVIEW/'inventory.json',review)
    write_json(REVIEW/'source-manifest.json',{'materials':old['materials'],'supplemental_materials':supplemental})
    sbom(review,REVIEW/'NutCase-0.6.0.spdx.json')
    with (REVIEW/'binary-inventory.csv').open('w',newline='',encoding='utf-8') as f:
        writer=csv.DictWriter(f,fieldnames=['path','sha256','component_name','component_version','license_expression','status','outstanding']);writer.writeheader()
        writer.writerows({k:r[k] for k in writer.fieldnames} for r in rows if Path(r['path']).suffix.lower() in ('.exe','.dll','.pyd'))
    (REVIEW/'COMPONENT_MATRIX.md').write_text('# NutCase current candidate component matrix\n\nVERIFIED describes the recorded technical evidence, not global legal certification. Exact per-file origins/hashes and source/SBOM references remain in inventory.json and source-manifest.json.\n\n| Component | Version | Selected terms | Files | Status | Evidence / remaining requirement |\n|---|---|---|---:|---|---|\n'+''.join(f"| {c['name']} | {c['version']} | {c['license_expression']} | {c['file_count']} | {c['status']} | {c['outstanding'] or 'Existing technical provenance/source/notices preserved; global human decisions still apply.'} |\n" for c in components),encoding='utf-8')
    write_json(OUT/'blocker-disposition.json',[{'id':c['id'],'kind':'component','original_status':c['status'],'current_status':next(n for n in components if n['id']==c['id'])['status'],'action_and_evidence':next(n for n in components if n['id']==c['id'])['outstanding']} for c in old['components'] if c['status'] not in ('VERIFIED','NOT APPLICABLE')]+[{'id':o['id'],'kind':'obligation','original_status':o['status'],'current_status':next(n for n in review['obligations'] if n['id']==o['id'])['status'],'action_and_evidence':next(n for n in review['obligations'] if n['id']==o['id'])['detail']} for o in old['obligations'] if o['status'] not in ('VERIFIED','NOT APPLICABLE')])
    print('Explicit audit:',len(rows),'files;',comparison['candidate_native_count'],'native;',len(removed),'excluded;',comparison['removed_bytes'],'bytes excluded')


if __name__=='__main__':main()
