"""Bind a review to an actually installed candidate after full payload comparison."""
import argparse
import json
import hashlib
from pathlib import Path
from research import ROOT,digest
from verify import confined


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--installed',type=Path,required=True)
    parser.add_argument('--installer',type=Path,required=True)
    args=parser.parse_args()
    args.installed=args.installed.resolve()
    args.installer=args.installer.resolve()
    path=ROOT/'packaging/licensing/inventory.json'
    review=json.loads(path.read_text(encoding='utf-8'))
    expected={r['path']:r for r in review['files']}
    actual={p.relative_to(args.installed).as_posix():p for p in args.installed.rglob('*') if p.is_file()}
    generated={'unins000.exe','unins000.dat'}
    if set(actual)-set(expected)!=generated:raise ValueError('Unexpected installed files: '+str(set(actual)-set(expected)))
    for name,row in expected.items():
        installed=confined(args.installed,name)
        if digest(installed)!=row['sha256']:raise ValueError('Installed payload differs: '+name)
    review['installer']={'path':args.installer.relative_to(ROOT).as_posix(),'sha256':digest(args.installer),
                         'version':'0.6.0','compiler':'Inno Setup 7.1.0','inspection':'Actual isolated installation, every file compared with separately recorded reviewed payload'}
    review['installer_generated_files']=[{'path':name,'sha256':digest(actual[name]),'component':'inno-runtime'} for name in sorted(generated)]
    path.write_text(json.dumps(review,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    installed_review={**review,'files':review['files']+[{'path':name,'installed_path':'{app}/'+name,
        'sha256':digest(actual[name]),'size':actual[name].stat().st_size,'component':'inno-runtime',
        'component_name':'Inno Setup generated uninstaller/runtime','component_version':'7.1.0',
        'license_expression':'LicenseRef-Inno-Setup','provenance':[{'installer_sha256':review['installer']['sha256'],
        'origin':'Generated by this exact installer during isolated installation'}]} for name in sorted(generated)]}
    output=args.installer.parent/'installed-inventory.json'
    output.write_text(json.dumps(installed_review,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    # Preserve SPDX file inventory as well as installer envelope identity.
    spdx_path=path.with_name('NutCase-0.6.0.spdx.json')
    spdx=json.loads(spdx_path.read_text(encoding='utf-8'))
    spdx['documentNamespace']='https://github.com/vscheff/NutCase/spdx/0.6.0/'+review['installer']['sha256']
    spdx_path.write_text(json.dumps(spdx,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    from assemble import sbom
    sbom(installed_review,args.installer.parent/'installed-NutCase-0.6.0.spdx.json')
    print('Actual installed payload matched:',len(expected),'files; generated runtime hashes retained; installer',review['installer']['sha256'])


if __name__=='__main__':main()
